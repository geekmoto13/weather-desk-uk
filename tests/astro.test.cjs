const assert=require('node:assert/strict');
global.window={};
require('../static/astro.js');
const a=window.WeatherAstro;
const lat=42.4668,lon=-70.9495,tz='America/New_York';
const local=(t)=>new Intl.DateTimeFormat('en-US',{timeZone:tz,hour:'2-digit',minute:'2-digit',hourCycle:'h23'}).format(t);
const october=a.calculate(Date.parse('2026-10-21T16:00:00Z'),lat,lon,tz);
assert.match(local(october.sun.rise),/^07:0[0-9]$/);
assert.match(local(october.sun.set),/^17:5[0-9]$/);
assert.ok(october.sun.rise<october.sun.set);
assert.ok(october.illumination.fraction>=0&&october.illumination.fraction<=1);
const summer=a.calculate(Date.parse('2026-06-21T16:00:00Z'),lat,lon,tz);
const winter=a.calculate(Date.parse('2026-12-21T16:00:00Z'),lat,lon,tz);
assert.ok(summer.sun.set-summer.sun.rise>14.5*3600000);
assert.ok(winter.sun.set-winter.sun.rise<10*3600000);
assert.equal(a.zonedMidnight(2026,3,9,tz)-a.zonedMidnight(2026,3,8,tz),23*3600000);
assert.equal(a.zonedMidnight(2026,11,2,tz)-a.zonedMidnight(2026,11,1,tz),25*3600000);
const polar=a.calculate(Date.parse('2026-06-21T12:00:00Z'),89,0,'UTC');
assert.equal(polar.sun.rise,null);
assert.equal(polar.sun.set,null);
assert.ok(polar.sun.alwaysUp);
const january=a.calculate(Date.parse('2026-01-31T23:00:00Z'),lat,lon,tz);
assert.equal(january.end-january.start,24*3600000);
console.log('Astronomical bounds, seasons, local dates and daylight-saving checks passed.');
