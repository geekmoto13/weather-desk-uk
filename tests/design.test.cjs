const assert=require('node:assert/strict');
const {chooseTheme,beacon}=require('../static/design.js');
const now=1792600000;
function forecast(summary,pop=0,extra={}){return {issuedAt:now-600,periods:Array.from({length:25},(_,i)=>({start:now-1800+i*3600,end:now-1800+(i+1)*3600,summary,pop})),...extra};}
assert.equal(beacon(forecast('Sunny'),now).kind,'clear');
assert.equal(beacon(forecast('Mostly Clear'),now).flash,false);
assert.equal(beacon(forecast('Partly Cloudy'),now).kind,'cloud');
assert.equal(beacon(forecast('Cloudy'),now).flash,true);
assert.equal(beacon(forecast('Chance Rain Showers',40),now).kind,'rain');
assert.equal(beacon(forecast('Thunderstorms',70),now).flash,false);
assert.equal(beacon(forecast('Snow',80),now).kind,'snow');
assert.equal(beacon(forecast('Freezing Rain',60),now).kind,'snow');
assert.equal(beacon(forecast('Slight Chance Rain Showers',20),now).kind,'cloud');
assert.equal(beacon(forecast('Rain',null),now).kind,'rain');
assert.equal(beacon(forecast('Chance Rain',null),now).kind,'cloud');
const mix={issuedAt:now-600,periods:[{start:now,end:now+39600,summary:'Rain',pop:70},{start:now+39600,end:now+43200,summary:'Chance Snow',pop:40}]};
assert.equal(beacon(mix,now).kind,'rain');
assert.equal(beacon(forecast('Sunny',0,{issuedAt:now-50000}),now).kind,'unknown');
assert.equal(beacon(forecast('Sunny',0,{error:'Service unavailable'}),now).kind,'unknown');
assert.equal(beacon(forecast('Sunny',0,{periods:[]}),now).kind,'unknown');
assert.equal(beacon(forecast('Sunny',0,{issuedAt:now+2000}),now).kind,'unknown');
assert.equal(beacon(forecast('Sunny',0,{demo:true}),now).demo,true);
assert.equal(chooseTheme('auto',-20,true,0,true),'night');
assert.equal(chooseTheme('auto',-2,true,0,true),'dawn');
assert.equal(chooseTheme('auto',2,false,100,true),'dusk');
assert.equal(chooseTheme('auto',35,true,650,true),'day');
assert.equal(chooseTheme('auto',35,true,40,true),'soft');
assert.equal(chooseTheme('auto',35,true,40,false),'day');
assert.equal(chooseTheme('auto',35,true,null,true),'day');
assert.equal(chooseTheme('dusk',35,true,900,true),'dusk');
console.log('Forecast beacon categories, stale/missing forecasts, precipitation thresholds and sky palette rules passed.');
