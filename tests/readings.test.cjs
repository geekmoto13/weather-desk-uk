const assert=require('node:assert/strict');
const {beaufort,withYearRain}=require('../static/readings.js');
assert.deepEqual(beaufort(0),{force:0,label:'Calm'});
assert.deepEqual(beaufort(1.8),{force:1,label:'Light air'});
assert.deepEqual(beaufort(10),{force:3,label:'Gentle breeze'});
for(const invalid of [null,undefined,NaN,Infinity,-1,'10',true])assert.equal(beaufort(invalid),null);
const thresholds=[.3,1.6,3.4,5.5,8,10.8,13.9,17.2,20.8,24.5,28.5,32.7];
thresholds.forEach((ms,i)=>{
  assert.equal(beaufort((ms-.00001)/.44704).force,i);
  assert.equal(beaufort(ms/.44704).force,i+1);
});
assert.equal(beaufort(200).force,12);
const stamp=Date.parse('2026-10-22T15:00:00Z')/1000;
const current={timestamp:stamp,rainYearMm:null,rainMonthMm:50,rainYearStatus:'missing'};
const row={timestamp:stamp-300,rainYearMm:900,rainYearStatus:'reported'};
let result=withYearRain(current,[row]);
assert.equal(result.rainYearMm,900);assert.equal(result.rainYearTimestamp,stamp-300);assert.equal(result.rainYearSource,'history');
assert.equal(current.rainYearMm,null,'Display fallback must not rewrite the live observation');
assert.equal(row.timestamp,stamp-300,'History must retain its own timestamp');
assert.equal(withYearRain({...current,rainYearMm:0},[row]).rainYearMm,0,'A reported zero takes priority over history');
assert.equal(withYearRain({...current,rainYearMm:0},[row]).rainYearSource,'live');
assert.equal(withYearRain(current,[{...row,timestamp:stamp-900}]).rainYearMm,900);
assert.equal(withYearRain(current,[{...row,timestamp:stamp-901}]).rainYearMm,null);
assert.equal(withYearRain(current,[{...row,timestamp:stamp+1}]).rainYearMm,null);
assert.equal(withYearRain({...current,rainYearStatus:'invalid'},[row]).rainYearMm,null);
assert.equal(withYearRain(current,[{...row,rainYearMm:-1}]).rainYearMm,null);
assert.equal(withYearRain(current,[row,{...row,timestamp:stamp-100,rainYearMm:910}]).rainYearMm,910);
assert.equal(withYearRain(current,[{...row,rainYearMm:null,totalrainin:100}]).rainYearMm,null,'A lifetime counter is never a year-to-date substitute');
assert.equal(withYearRain(current,[]).rainYearMm,null,'Partial monthly history must not become a yearly total');
const jan1=Date.parse('2027-01-01T05:02:00Z')/1000;
assert.equal(withYearRain({...current,timestamp:jan1},[{...row,timestamp:jan1-300}]).rainYearMm,null,'Never carry last year’s counter across local New Year');
assert.equal(withYearRain({...current,timestamp:jan1-180},[{...row,timestamp:jan1-300}]).rainYearMm,900,'UTC New Year alone does not reset the local calendar year');
assert.equal(withYearRain(null),null);
console.log('Beaufort thresholds and yearly rain priority, freshness, missing/zero values and local New Year checks passed.');

const annual={complete:true,timezone:'America/New_York',year:2026,start:'2026-01-01',through:'2026-10-22',timestamp:stamp,mm:26.72*25.4};
let calculated=withYearRain(current,[],'America/New_York',annual);
assert.equal(calculated.rainYearSource,'calculated');assert.equal(calculated.rainYearMm,26.72*25.4);
assert.equal(withYearRain({...current,rainYearMm:26.72*25.4},[],'America/New_York',{...annual,mm:25*25.4}).rainYearMm,26.72*25.4,'A provider annual total takes priority over a different reconstructed total');
assert.equal(withYearRain({...current,rainYearMm:0},[],'America/New_York',annual).rainYearSource,'live','A real reported zero must not be hidden by a calculation');
for(const override of [{complete:false},{through:'2026-10-21'},{start:'2026-07-01'},{year:2025},{timezone:'UTC'},{timestamp:stamp-901},{mm:null}])assert.equal(withYearRain(current,[],'America/New_York',{...annual,...override}).rainYearMm,null);
console.log('Calculated calendar-year totals, date alignment, freshness and reported-counter priority passed.');
